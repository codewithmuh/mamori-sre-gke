const pathCatalog = "slo/generated/slo-catalog.md"

// renderCatalog writes a human-readable list of everything generated: per
// journey the critical services, the SLOs with their budgets, the alerts and
// the queries to check them. Runbooks and the incident agent link here.
func (m *Model) renderCatalog() File {
	var b strings.Builder
	sp := m.Spec
	md := m.Map.Metadata
	fmt.Fprintf(&b, "<!-- %s -->\n\n", strings.Join(m.HeaderLines(), "\n     "))
	b.WriteString("# CUJ SLO catalog\n\n")
	fmt.Fprintf(&b, "Generated from `%s` and the CUJ map `%s`", m.Inputs.SLOs, m.Inputs.CUJMap)
	if md.GeneratedAt != "" {
		fmt.Fprintf(&b, " (made %s by %s, Online Boutique %s, %d runs per case; a service is critical when the journey fails in at least %s %% of runs with it broken)",
			md.GeneratedAt, orUnknown(md.Generator), orUnknown(md.OnlineBoutique), md.RunsPerCase, percent(md.FailureThreshold))
	}
	b.WriteString(". Design: [docs/slo/slo-design.md](../../docs/slo/slo-design.md). Do not edit this file; edit the inputs and run `make slo-generate`.\n\n")
	fmt.Fprintf(&b, "Every SLO uses a rolling %s window. Budgets are the share of events (or minutes) that may be bad in that window.\n\n", sp.Window)

	b.WriteString("## Alert tiers\n\n")
	b.WriteString("Each tier pages or opens a ticket when the burn rate is above the threshold over both windows.\n\n")
	b.WriteString("| Tier | Severity | Burn rate above | Long window | Short window | Budget spent in the long window | Signals |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")
	for _, t := range sp.Alerting.Tiers {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", t.Name, t.Severity, formatFloat(BurnRate(t, sp.Window)),
			t.LongWindow, t.ShortWindow, budgetShare(t), strings.Join(t.Signals, ", "))
	}
	fmt.Fprintf(&b, "\nPlus one `CUJ <id>: prober no data` policy per journey (page) after %s without prober data.\n", sp.Alerting.NoDataAfter)
	b.WriteString("Every Cloud Monitoring policy carries the user labels `cuj`, `signal`, `sli`, `alert` (`burn-rate` or `no-data`), " +
		"`burn` (tier name, or `none`), `severity` (`page` or `ticket`) and `generator=slo-gen`.\n\n")

	for _, j := range m.Journeys {
		m.catalogJourney(&b, j)
	}
	return File{Path: pathCatalog, Content: []byte(b.String())}
}

func (m *Model) catalogJourney(b *strings.Builder, j Journey) {
	sp := m.Spec
	fmt.Fprintf(b, "## %s\n\n", j.ID)
	fmt.Fprintf(b, "- Runbook: [docs/runbooks/cuj-%s.md](../../docs/runbooks/cuj-%s.md)\n", j.ID, j.ID)
	fmt.Fprintf(b, "- Critical services (CUJ map): %s\n", listOrNone(j.Critical))
	fmt.Fprintf(b, "- Mesh composite over: %s", strings.Join(j.MeshServices, ", "))
	if len(j.TCPSkipped) > 0 {
		fmt.Fprintf(b, " (left out, plain TCP: %s)", strings.Join(j.TCPSkipped, ", "))
	}
	b.WriteString("\n")
	fmt.Fprintf(b, "- Prober latency steps: %s\n", strings.Join(j.ProberSteps, ", "))
	fmt.Fprintf(b, "- Cloud Monitoring service: `%s`\n\n", serviceID(j))

	fmt.Fprintf(b, "| SLO id | What counts as good | Target | Budget in %s | Recorded series (PromQL) |\n", sp.Window)
	b.WriteString("|---|---|---|---|---|\n")
	for _, s := range j.SLOs {
		fmt.Fprintf(b, "| `%s` | %s | %s %% | %s | `%s` |\n", s.ID(), sloDescription(j, s), percent(s.Target),
			m.budgetText(s), selector(recCUJ(s.Signal, s.SLI, m.recordWindow(s)), matcher("cuj", "=", j.ID)))
	}
	if sp.Datadog.BurnRate.Enabled {
		fmt.Fprintf(b, "| Datadog `%s` | synthetics runs passed (%s) | %s %% | %s %% of runs | n/a |\n",
			tfName(j.ID, "synthetics", "runs"), strings.Join(sp.Datadog.Timeframes, ", "), percent(j.Availability.Target), percent(1-j.Availability.Target))
	}
	fmt.Fprintf(b, "| Datadog `%s` | time the synthetics monitor is OK (%s) | %s %% | %s %% of the time | n/a |\n\n",
		tfName(j.ID, "synthetics", "availability"), strings.Join(sp.Datadog.Timeframes, ", "), percent(j.Availability.Target), percent(1-j.Availability.Target))

	b.WriteString("Alert policies (Cloud Monitoring display names):\n\n")
	for _, s := range j.SLOs {
		for _, t := range m.TiersFor(s.Signal) {
			fmt.Fprintf(b, "- `CUJ %s: %s %s %s burn` (%s, burn rate > %s)\n", j.ID, s.Signal, s.SLI, t.Name, t.Severity, formatFloat(BurnRate(t, sp.Window)))
		}
	}
	fmt.Fprintf(b, "- `CUJ %s: prober no data` (page)\n\n", j.ID)
}

func (m *Model) recordWindow(s SLO) Duration {
	if s.Signal == signalMesh {
		return m.Spec.Mesh.SLORateWindow
	}
	return m.Spec.Prober.RecordWindows[0]
}

// budgetText describes the error budget. The prober runs once a minute and the
// mesh SLOs count minutes, so both availability budgets come out in minutes.
func (m *Model) budgetText(s SLO) string {
	bad := 1 - s.Target
	switch {
	case s.Signal == signalMesh:
		windows := float64(m.Spec.Window.D() / m.Spec.Mesh.WindowPeriod.D())
		return fmt.Sprintf("%s bad %s windows", formatFloat(math.Floor(bad*windows)), m.Spec.Mesh.WindowPeriod)
	case s.SLI == sliAvailability:
		runs := m.Spec.Window.D() / time.Minute
		return fmt.Sprintf("%s failed runs (at one run a minute)", formatFloat(math.Floor(bad*float64(runs))))
	default:
		return fmt.Sprintf("%s %% of successful steps over the threshold", percent(bad))
	}
}
