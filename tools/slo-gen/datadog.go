package main

import (
	"fmt"
	"slices"
	"strings"
)

const pathDatadogTF = "infra/envs/datadog/slo_generated.tf.json"

// Datadog resources reference the synthetics tests of infra/envs/datadog
// (datadog_synthetics_test.cuj_<id>) and that root's locals datadog_tags,
// runbook_base_url and notify; none of them are declared here.
func synthRef(j Journey, attr string) string {
	return fmt.Sprintf("${datadog_synthetics_test.cuj_%s.%s}", snake(j.ID), attr)
}

func datadogTags(j Journey, extra ...string) string {
	tags := append([]string{"cuj:" + j.ID, "generator:slo-gen"}, extra...)
	q := make([]string, len(tags))
	for i, t := range tags {
		q[i] = fmt.Sprintf("%q", t)
	}
	return fmt.Sprintf("${concat(local.datadog_tags, [%s])}", strings.Join(q, ", "))
}

func (m *Model) datadogThresholds(target float64) []obj {
	out := make([]obj, len(m.Spec.Datadog.Timeframes))
	for i, f := range m.Spec.Datadog.Timeframes {
		out[i] = obj{"timeframe": f, "target": round4(target * 100)}
	}
	return out
}

// monitorSLO is the journey's availability as Datadog sees it from outside:
// the share of time the synthetics test's monitor was not alerting.
func (m *Model) monitorSLO(j Journey) obj {
	main := m.Spec.Datadog.Timeframes[0]
	return obj{
		"name": fmt.Sprintf("CUJ %s: synthetics availability", j.ID),
		"type": "monitor",
		"description": fmt.Sprintf("Share of time the %s synthetics test passes, from outside Google Cloud. "+
			"Runbook: %s. Generated by slo-gen from slo/slos.yaml.", j.ID, runbookRef(j)),
		"monitor_ids":      []string{synthRef(j, "monitor_id")},
		"thresholds":       m.datadogThresholds(j.Availability.Target),
		"timeframe":        main,
		"target_threshold": round4(j.Availability.Target * 100),
		"tags":             datadogTags(j, "signal:synthetics", "sli:availability"),
	}
}

// runsSLO counts passed test runs over all runs. It exists to carry the
// burn-rate monitors, which Datadog does not allow on Synthetics monitor SLOs.
func (m *Model) runsSLO(j Journey) obj {
	br := m.Spec.Datadog.BurnRate
	scope := br.TestTag + ":" + synthRef(j, "id")
	return obj{
		"name": fmt.Sprintf("CUJ %s: synthetics runs passed", j.ID),
		"type": "metric",
		"description": fmt.Sprintf("Passed runs of the %s synthetics test over all runs; source of the burn-rate monitors. "+
			"Runbook: %s. Generated by slo-gen from slo/slos.yaml.", j.ID, runbookRef(j)),
		"query": []obj{{
			"numerator":   fmt.Sprintf("sum:%s{%s,%s}.as_count()", br.Metric, scope, br.GoodFilter),
			"denominator": fmt.Sprintf("sum:%s{%s}.as_count()", br.Metric, scope),
		}},
		"thresholds":       m.datadogThresholds(j.Availability.Target),
		"timeframe":        m.Spec.Datadog.Timeframes[0],
		"target_threshold": round4(j.Availability.Target * 100),
		"tags":             datadogTags(j, "signal:synthetics", "sli:availability"),
	}
}

func runbookRef(j Journey) string { return "${local.runbook_base_url}/cuj-" + j.ID + ".md" }

func datadogPriority(severity string) string {
	if severity == severityPage {
		return "1"
	}
	return "3"
}

// datadogTiers are the availability tiers named in datadog.tiers, with short
// windows of at least datadog.minShortWindow. A test that runs every 5 minutes
// from one location has 0 or 1 runs in a 5-minute window, so a short window
// that small flaps.
func (m *Model) datadogTiers() []TierSpec {
	var out []TierSpec
	for _, t := range m.Spec.Alerting.AvailabilityTiers {
		if !slices.Contains(m.Spec.Datadog.Tiers, t.Name) {
			continue
		}
		if t.ShortWindow < m.Spec.Datadog.MinShortWindow {
			t.ShortWindow = m.Spec.Datadog.MinShortWindow
		}
		out = append(out, t)
	}
	return out
}

func (m *Model) burnMonitor(j Journey, t TierSpec) obj {
	burn := formatFloat(BurnRate(t, m.Spec.Window))
	severity := m.Severity(signalSynthetics, t)
	slo := fmt.Sprintf("${datadog_service_level_objective.%s.id}", tfName(j.ID, "synthetics", "runs"))
	frame := m.Spec.Datadog.Timeframes[0]
	msg := fmt.Sprintf("The %s journey, seen by Datadog synthetics, is spending its error budget at least %s times "+
		"faster than allowed, over both the last %s and the last %s (alert tier %s, %s).\n\n"+
		"Runbook: %s\n\n"+
		"Generated by slo-gen from slo/slos.yaml; change it there, not here. ${local.notify}",
		j.ID, burn, t.LongWindow, t.ShortWindow, t.Name, severity, runbookRef(j))
	return obj{
		"name":               fmt.Sprintf("CUJ %s: synthetics availability %s burn", j.ID, t.Name),
		"type":               "slo alert",
		"query":              fmt.Sprintf("burn_rate(\"%s\").over(\"%s\").long_window(\"%s\").short_window(\"%s\") > %s", slo, frame, t.LongWindow, t.ShortWindow, burn),
		"message":            msg,
		"monitor_thresholds": []obj{{"critical": burn}},
		"priority":           datadogPriority(severity),
		"tags":               datadogTags(j, "signal:synthetics", "sli:availability", "alert:burn-rate", "burn:"+t.Name, "severity:"+severity),
	}
}

func (m *Model) renderDatadog() (File, error) {
	slos := obj{}
	monitors := obj{}
	for _, j := range m.Journeys {
		slos[tfName(j.ID, "synthetics", "availability")] = m.monitorSLO(j)
		if !m.Spec.Datadog.BurnRate.Enabled {
			continue
		}
		slos[tfName(j.ID, "synthetics", "runs")] = m.runsSLO(j)
		for _, t := range m.datadogTiers() {
			monitors[tfName(j.ID, "synthetics", t.Name)] = m.burnMonitor(j, t)
		}
	}
	resources := obj{"datadog_service_level_objective": slos}
	if len(monitors) > 0 {
		resources["datadog_monitor"] = monitors
	}
	b, err := encodeJSON(obj{"//": m.Header(), "resource": resources})
	return File{Path: pathDatadogTF, Content: b}, err
}
