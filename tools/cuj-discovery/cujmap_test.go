func TestBuildMapThreshold(t *testing.T) {
	opts := options{
		CUJs:      []string{"view-cart", "browse"},
		Targets:   []target{{"adservice", methodGRPCAbort}, {"cartservice", methodGRPCAbort}, {"shippingservice", methodGRPCAbort}},
		Threshold: 0.5,
	}
	res := results{}
	// 9 of 20 (0.45) is below the threshold; 10 of 20 (0.5) is at it, so critical.
	res.add("browse", "adservice", caseResult{Runs: 20, Failures: 9})
	res.add("browse", "cartservice", caseResult{Runs: 20, Failures: 10})
	res.add("browse", "shippingservice", caseResult{Runs: 20, Failures: 0})
	res.add("view-cart", "adservice", caseResult{Runs: 20, Failures: 0})
	res.add("view-cart", "cartservice", caseResult{Runs: 20, Failures: 20})
	res.add("view-cart", "shippingservice", caseResult{Runs: 20, Failures: 20})
	m := buildMap(res, opts, testMeta())
	if len(m.Journeys) != 2 || m.Journeys[0].ID != "browse" {
		t.Fatalf("journeys not sorted: %+v", m.Journeys)
	}
	b := m.Journeys[0]
	if !slices.Equal(b.Critical, []string{"cartservice"}) || !slices.Equal(b.NonCritical, []string{"adservice", "shippingservice"}) {
		t.Errorf("browse = %+v", b)
	}
	if b.Results["adservice"].FailureRate != 0.45 {
		t.Errorf("rate = %v", b.Results["adservice"].FailureRate)
	}
	if err := validateMap(m); err != nil {
		t.Fatal(err)
	}

	data, err := renderMap(m)
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range []string{
		"# Generated by tools/cuj-discovery",
		"apiVersion: mamori/v1\nkind: CUJMap\n",
		"critical: [cartservice]",
		"nonCritical: [adservice, shippingservice]",
		"adservice: {failureRate: 0.45, runs: 20}",
		"shippingservice: {failureRate: 0.0, runs: 20}",
		"cartservice: {failureRate: 1.0, runs: 20}",
	} {
		if !strings.Contains(string(data), s) {
			t.Errorf("rendered map lacks %q:\n%s", s, data)
		}
	}
	again, _ := renderMap(buildMap(res, opts, testMeta()))
	if string(again) != string(data) {
		t.Error("rendering is not deterministic")
	}
	back, err := parseCUJMap(data)
	if err != nil {
		t.Fatalf("round trip: %v", err)
	}
	if back.Journeys[1].Results["shippingservice"] != (serviceResult{FailureRate: 1, Runs: 20}) {
		t.Errorf("round trip lost data: %+v", back.Journeys[1])
	}
}

func TestFormatRate(t *testing.T) {
	for in, want := range map[float64]string{0: "0.0", 1: "1.0", 0.35: "0.35", 1.0 / 3: "0.3333", 0.05: "0.05"} {
		if got := formatRate(in); got != want {
			t.Errorf("formatRate(%v) = %q, want %q", in, got, want)
		}
	}
}

