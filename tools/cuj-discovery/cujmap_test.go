func TestValidateMapErrors(t *testing.T) {
	good := func() cujMap {
		return cujMap{APIVersion: mapAPIVersion, Kind: mapKind, Metadata: testMeta(), Journeys: []journey{{
			ID:          "browse",
			Critical:    []string{"cartservice"},
			NonCritical: []string{"adservice"},
			Results:     map[string]serviceResult{"cartservice": {1, 20}, "adservice": {0, 20}},
		}}}
	}
	if err := validateMap(good()); err != nil {
		t.Fatalf("good map rejected: %v", err)
	}
	cases := []struct {
		name   string
		mutate func(*cujMap)
		want   string
	}{
		{"kind", func(m *cujMap) { m.Kind = "Map" }, "apiVersion/kind"},
		{"time", func(m *cujMap) { m.Metadata.GeneratedAt = "yesterday" }, "not RFC 3339"},
		{"generator", func(m *cujMap) { m.Metadata.Generator = "me" }, "metadata.generator"},
		{"fault", func(m *cujMap) { m.Metadata.Fault = "" }, "metadata.fault must be set"},
		{"runs", func(m *cujMap) { m.Metadata.RunsPerCase = 0 }, "runsPerCase 0"},
		{"threshold", func(m *cujMap) { m.Metadata.FailureThreshold = 1.5 }, "failureThreshold 1.5"},
		{"no journeys", func(m *cujMap) { m.Journeys = nil }, "no journeys"},
		{"unknown journey", func(m *cujMap) { m.Journeys[0].ID = "search" }, `journey "search"`},
		{"duplicate journey", func(m *cujMap) { m.Journeys = append(m.Journeys, m.Journeys[0]) }, "appears twice"},
		{"unsorted", func(m *cujMap) {
			m.Journeys[0].NonCritical = []string{"redis-cart", "adservice"}
			m.Journeys[0].Results["redis-cart"] = serviceResult{0, 20}
		}, "nonCritical must be sorted"},
		{"both lists", func(m *cujMap) { m.Journeys[0].NonCritical = []string{"adservice", "cartservice"} }, "both critical and nonCritical"},
		{"listed without result", func(m *cujMap) { m.Journeys[0].Critical = []string{"cartservice", "paymentservice"} }, "paymentservice is listed but has no result"},
		{"result without list", func(m *cujMap) { m.Journeys[0].Results["emailservice"] = serviceResult{0, 20} }, "emailservice has failureRate 0 and threshold 0.5, so it belongs in nonCritical"},
		{"wrong list", func(m *cujMap) { m.Journeys[0].Results["adservice"] = serviceResult{0.9, 20} }, "belongs in critical"},
		{"rate range", func(m *cujMap) { m.Journeys[0].Results["cartservice"] = serviceResult{2, 20} }, "failureRate 2, want 0-1"},
		{"runs differ", func(m *cujMap) { m.Journeys[0].Results["cartservice"] = serviceResult{1, 5} }, "runs 5"},
		{"unknown service", func(m *cujMap) {
			m.Journeys[0].Results["frontend"] = serviceResult{1, 20}
			m.Journeys[0].Critical = []string{"cartservice", "frontend"}
		}, "frontend is not an upstream service"},
		{"no results", func(m *cujMap) {
			m.Journeys[0].Results = nil
			m.Journeys[0].Critical, m.Journeys[0].NonCritical = nil, nil
		}, "no results"},
	}
	for _, c := range cases {
		m := good()
		c.mutate(&m)
		err := validateMap(m)
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%s: err = %v, want %q", c.name, err, c.want)
		}
	}
}

func TestParseCUJMapStrict(t *testing.T) {
	if _, err := parseCUJMap([]byte("apiVersion: mamori/v1\nkind: CUJMap\nextra: 1\n")); err == nil || !strings.Contains(err.Error(), "field extra not found") {
		t.Errorf("unknown field accepted: %v", err)
	}
	if _, err := parseCUJMap([]byte("{")); err == nil {
		t.Error("broken YAML accepted")
	}
}

func TestWriteFileAtomic(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "a", "b", "map.yaml")
	if err := writeFileAtomic(path, []byte("one")); err != nil {
		t.Fatal(err)
	}
	if err := writeFileAtomic(path, []byte("two")); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadFile(path)
	if string(got) != "two" {
		t.Errorf("content = %q", got)
	}
	entries, _ := os.ReadDir(filepath.Dir(path))
	if len(entries) != 1 {
		t.Errorf("temporary files left: %v", entries)
	}
	if err := writeFileAtomic(filepath.Join(path, "below-a-file.yaml"), nil); err == nil {
		t.Error("writing below a file should fail")
	}
}
