// The CUJ map schema is fixed by the build contract; slo-gen (#18), the
// incident docs (#20) and the agent evaluation (#26) read it.
const (
	mapAPIVersion = "mamori/v1"
	mapKind       = "CUJMap"
)

type cujMap struct {
	APIVersion string      `yaml:"apiVersion"`
	Kind       string      `yaml:"kind"`
	Metadata   mapMetadata `yaml:"metadata"`
	Journeys   []journey   `yaml:"journeys"`
}

type mapMetadata struct {
	GeneratedAt      string  `yaml:"generatedAt"`
	Generator        string  `yaml:"generator"`
	OnlineBoutique   string  `yaml:"onlineBoutique"`
	RunsPerCase      int     `yaml:"runsPerCase"`
	FailureThreshold float64 `yaml:"failureThreshold"`
	Fault            string  `yaml:"fault"`
}

type journey struct {
	ID          string                   `yaml:"id"`
	Critical    []string                 `yaml:"critical,flow"`
	NonCritical []string                 `yaml:"nonCritical,flow"`
	Results     map[string]serviceResult `yaml:"results"`
}

type serviceResult struct {
	FailureRate float64 `yaml:"failureRate"`
	Runs        int     `yaml:"runs"`
}

// MarshalYAML writes one result per line, {failureRate: 0.35, runs: 20}, with
// the rate always written as a decimal.
func (r serviceResult) MarshalYAML() (any, error) {
	return &yaml.Node{Kind: yaml.MappingNode, Style: yaml.FlowStyle, Content: []*yaml.Node{
		{Kind: yaml.ScalarNode, Value: "failureRate"},
		{Kind: yaml.ScalarNode, Tag: "!!float", Value: formatRate(r.FailureRate)},
		{Kind: yaml.ScalarNode, Value: "runs"},
		{Kind: yaml.ScalarNode, Tag: "!!int", Value: strconv.Itoa(r.Runs)},
	}}, nil
}

func formatRate(r float64) string {
	s := strconv.FormatFloat(math.Round(r*1e4)/1e4, 'f', -1, 64)
	if !strings.Contains(s, ".") {
		s += ".0"
	}
	return s
}

// faultDescription goes into metadata.fault.
func faultDescription(settle time.Duration) string {
	return fmt.Sprintf("one service at a time: Istio VirtualService abort of 100 %% of requests with gRPC status UNAVAILABLE "+
		"(redis-cart, plain TCP: Deployment scaled to 0 replicas); measured %s after the fault was in place", settle)
}

// buildMap classifies every (journey, service) case. A service is critical
// for a journey when the journey's failure rate with the service broken is at
// least the threshold. Lists and journeys are sorted, so the same results
// always give the same file.
func buildMap(res results, opts options, meta mapMetadata) cujMap {
	m := cujMap{APIVersion: mapAPIVersion, Kind: mapKind, Metadata: meta}
	cujs := slices.Clone(opts.CUJs)
	slices.Sort(cujs)
	for _, cuj := range cujs {
		j := journey{ID: cuj, Critical: []string{entryService}, NonCritical: []string{}, Results: map[string]serviceResult{}}
		for _, t := range opts.Targets {
			c := res[cuj][t.Service]
			j.Results[t.Service] = serviceResult{FailureRate: c.rate(), Runs: c.Runs}
			if c.rate() >= opts.Threshold {
				j.Critical = append(j.Critical, t.Service)
			} else {
				j.NonCritical = append(j.NonCritical, t.Service)
			}
		}
		slices.Sort(j.Critical)
		slices.Sort(j.NonCritical)
		m.Journeys = append(m.Journeys, j)
	}
	return m
}

const mapHeader = `# Generated by tools/cuj-discovery from fault injection. Do not edit by hand: re-run
# "make discovery-run". How to read it: docs/slo/cuj-discovery.md.
`

func renderMap(m cujMap) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(mapHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(m); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// writeFileAtomic replaces path in one step, so a crash never leaves half a
// map for slo-gen to read.
func writeFileAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".cuj-map-*.yaml")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil { //nolint:gosec // a public file in the repo
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// parseCUJMap reads a map strictly (unknown fields are errors) and checks it.
func parseCUJMap(data []byte) (cujMap, error) {
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	var m cujMap
	if err := dec.Decode(&m); err != nil {
		return cujMap{}, fmt.Errorf("parse: %w", err)
	}
	return m, validateMap(m)
}

// validateMap checks the rules readers rely on: known ids, sorted and
// disjoint lists that cover exactly the measured services plus the frontend,
// and lists that agree with the failure rates and the threshold.
func validateMap(m cujMap) error {
	var errs []error
	bad := func(format string, a ...any) { errs = append(errs, fmt.Errorf(format, a...)) }

	if m.APIVersion != mapAPIVersion || m.Kind != mapKind {
		bad("apiVersion/kind is %s/%s, want %s/%s", m.APIVersion, m.Kind, mapAPIVersion, mapKind)
	}
	md := m.Metadata
	if _, err := time.Parse(time.RFC3339, md.GeneratedAt); err != nil {
		bad("metadata.generatedAt %q is not RFC 3339", md.GeneratedAt)
	}
	if !strings.HasPrefix(md.Generator, "cuj-discovery/") {
		bad("metadata.generator %q must start with cuj-discovery/", md.Generator)
	}
	if md.OnlineBoutique == "" || md.Fault == "" {
		bad("metadata.onlineBoutique and metadata.fault must be set")
	}
	if md.RunsPerCase < 1 || md.RunsPerCase > maxProberRuns {
		bad("metadata.runsPerCase %d must be 1-%d", md.RunsPerCase, maxProberRuns)
	}
	if t := md.FailureThreshold; math.IsNaN(t) || t <= 0 || t > 1 {
		bad("metadata.failureThreshold %g must be above 0 and at most 1", md.FailureThreshold)
	}
	if len(m.Journeys) == 0 {
		bad("no journeys")
	}

	seen := map[string]bool{}
	for _, j := range m.Journeys {
		if !slices.Contains(allCUJs, j.ID) {
			bad("journey %q is not one of %s", j.ID, strings.Join(allCUJs, ", "))
		}
		if seen[j.ID] {
			bad("journey %q appears twice", j.ID)
		}
		seen[j.ID] = true
		errs = append(errs, validateJourney(j, md)...)
	}
	return errors.Join(errs...)
}

// checkComplete reports journeys or services a map is missing. slo-gen's map
// must be complete; maps from runs with -cujs or -services are not.
func checkComplete(m cujMap) error {
	var errs []error
	for _, id := range allCUJs {
		i := slices.IndexFunc(m.Journeys, func(j journey) bool { return j.ID == id })
		if i < 0 {
			errs = append(errs, fmt.Errorf("journey %s is missing", id))
			continue
		}
		for _, t := range allTargets {
			if _, ok := m.Journeys[i].Results[t.Service]; !ok {
				errs = append(errs, fmt.Errorf("journey %s: %s was not measured", id, t.Service))
			}
		}
	}
	if len(errs) > 0 {
		errs = append(errs, errors.New("incomplete map: it comes from a run with -cujs or -services (validate --partial accepts it)"))
	}
	return errors.Join(errs...)
}

func validateJourney(j journey, md mapMetadata) []error {
	var errs []error
	bad := func(format string, a ...any) {
		errs = append(errs, fmt.Errorf("journey %s: "+format, append([]any{j.ID}, a...)...))
	}

	for _, l := range []struct {
		name string
		list []string
	}{{"critical", j.Critical}, {"nonCritical", j.NonCritical}} {
		if !slices.IsSorted(l.list) || len(slices.Compact(slices.Clone(l.list))) != len(l.list) {
			bad("%s must be sorted with no duplicates", l.name)
		}
	}
	listed := map[string]string{}
	for _, s := range j.Critical {
		listed[s] = "critical"
	}
	for _, s := range j.NonCritical {
		if listed[s] != "" {
			bad("%s is both critical and nonCritical", s)
		}
		listed[s] = "nonCritical"
	}
	if !slices.Contains(j.Critical, entryService) {
		bad("%s must be in critical: every step of every journey is a request to it", entryService)
	}
	if len(j.Results) == 0 {
		bad("no results")
	}
	for _, s := range append(slices.Clone(j.Critical), j.NonCritical...) {
		if _, ok := j.Results[s]; !ok && s != entryService {
			bad("%s is listed but has no result", s)
		}
	}
	services := make([]string, 0, len(j.Results))
	for s := range j.Results {
		services = append(services, s)
	}
	slices.Sort(services)
	for _, s := range services {
		r := j.Results[s]
		if !slices.ContainsFunc(allTargets, func(t target) bool { return t.Service == s }) {
			bad("%s is not an upstream service", s)
		}
		if r.Runs != md.RunsPerCase {
			bad("%s has runs %d, metadata.runsPerCase is %d", s, r.Runs, md.RunsPerCase)
		}
		if r.FailureRate < 0 || r.FailureRate > 1 {
			bad("%s has failureRate %g, want 0-1", s, r.FailureRate)
		}
		want := "nonCritical"
		if r.FailureRate >= md.FailureThreshold {
			want = "critical"
		}
		if listed[s] != want {
			bad("%s has failureRate %g and threshold %g, so it belongs in %s", s, r.FailureRate, md.FailureThreshold, want)
		}
	}
	return errs
}
